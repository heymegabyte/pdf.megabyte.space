export function getTemplate(slug: string): TemplateHubEntry | undefined {
  return TEMPLATES.find((t) => t.slug === slug);
}

export function templatesByCategory(category: TemplateCategory): TemplateHubEntry[] {
  return TEMPLATES.filter((t) => t.category === category);
}

export function relatedTemplates(slug: string, count = 4): TemplateHubEntry[] {
  const current = getTemplate(slug);
  if (!current) return TEMPLATES.slice(0, count);
  const sameCat = TEMPLATES.filter((t) => t.slug !== slug && t.category === current.category);
  const others = TEMPLATES.filter((t) => t.slug !== slug && t.category !== current.category);
  return [...sameCat, ...others].slice(0, count);
}
